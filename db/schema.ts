/**
 * Estrutura do banco de dados.
 *
 * Todos os comandos são idempotentes ("if not exists") e rodam automaticamente
 * na primeira consulta de cada instância do servidor — em produção (Neon) e em
 * desenvolvimento (PGlite). Não é preciso executar SQL manualmente.
 *
 * Para evoluir o banco, acrescente novos comandos idempotentes ao FINAL da lista.
 */
export const schemaStatements = [
  // Pedidos de agendamento feitos pelas clientes.
  `create table if not exists bookings (
    id bigint generated by default as identity primary key,
    name text not null check (char_length(name) between 2 and 80),
    service_id text not null,
    service_title text not null,
    date date not null,
    time text not null,
    note text not null default '',
    status text not null default 'pending' check (status in ('pending', 'confirmed', 'completed', 'cancelled')),
    created_at bigint not null default (extract(epoch from now()) * 1000)::bigint
  )`,
  `create index if not exists idx_bookings_created_at on bookings (created_at desc)`,
  // Um mesmo horário nunca tem dois pedidos ativos.
  `create unique index if not exists idx_bookings_date_time_unique
    on bookings (date, time)
    where status <> 'cancelled'`,

  // Horários que a Maysa disponibiliza. Dia sem horários = dia fechado.
  `create table if not exists availability_slots (
    date date not null,
    time text not null check (time ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
    created_at bigint not null default (extract(epoch from now()) * 1000)::bigint,
    primary key (date, time)
  )`,
  `create index if not exists idx_availability_slots_date on availability_slots (date)`,
];
